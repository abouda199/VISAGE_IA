import pygame
import sys

from face.face_engine import (
    FaceEngine
)


# ============================================================
# INITIALISATION
# ============================================================

pygame.init()


# ============================================================
# CONFIGURATION
# ============================================================

WIDTH = 900
HEIGHT = 600
FPS = 60


screen = pygame.display.set_mode(
    (
        WIDTH,
        HEIGHT
    )
)

pygame.display.set_caption(
    "VISAGE AI"
)

clock = pygame.time.Clock()


# ============================================================
# CREATION DU VISAGE
# ============================================================

face = FaceEngine(
    WIDTH,
    HEIGHT
)


# ============================================================
# BOUCLE
# ============================================================

running = True


while running:

    dt = (
        clock.tick(FPS)
        / 1000.0
    )

    # ========================================================
    # EVENEMENTS
    # ========================================================

    for event in pygame.event.get():

        if event.type == pygame.QUIT:

            running = False


        if event.type == pygame.KEYDOWN:

            # -----------------------------------------------
            # NEUTRAL
            # -----------------------------------------------

            if event.key == pygame.K_1:

                face.set_emotion(
                    "neutral"
                )

            # -----------------------------------------------
            # HAPPY
            # -----------------------------------------------

            elif event.key == pygame.K_2:

                face.set_emotion(
                    "happy",
                    1.0
                )

            # -----------------------------------------------
            # SAD
            # -----------------------------------------------

            elif event.key == pygame.K_3:

                face.set_emotion(
                    "sad",
                    1.0
                )

            # -----------------------------------------------
            # ANGRY
            # -----------------------------------------------

            elif event.key == pygame.K_4:

                face.set_emotion(
                    "angry",
                    1.0
                )

            # -----------------------------------------------
            # SURPRISED
            # -----------------------------------------------

            elif event.key == pygame.K_5:

                face.set_emotion(
                    "surprised",
                    1.0
                )

            # -----------------------------------------------
            # TALKING
            # -----------------------------------------------

            elif event.key == pygame.K_6:

                face.set_emotion(
                    "talking",
                    1.0
                )

            # -----------------------------------------------
            # THINKING
            # -----------------------------------------------

            elif event.key == pygame.K_7:

                face.set_emotion(
                    "thinking",
                    1.0
                )

            # -----------------------------------------------
            # LISTENING
            # -----------------------------------------------

            elif event.key == pygame.K_8:

                face.set_emotion(
                    "listening",
                    1.0
                )

            # -----------------------------------------------
            # HAPPY LEGER
            # -----------------------------------------------

            elif event.key == pygame.K_9:

                face.set_emotion(
                    "happy",
                    0.35
                )

            # -----------------------------------------------
            # QUITTER
            # -----------------------------------------------

            elif event.key == pygame.K_ESCAPE:

                running = False


    # ========================================================
    # UPDATE
    # ========================================================

    face.update(dt)


    # ========================================================
    # DRAW
    # ========================================================

    face.draw(
        screen
    )


    pygame.display.flip()


# ============================================================
# FIN
# ============================================================

pygame.quit()

sys.exit()